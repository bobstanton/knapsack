// The playground's completion and pairing logic is not part of the knap npm package, so it is copied from a checkout.
import esbuild from "esbuild";
import { execFileSync } from "node:child_process";
import { promises as fs } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const knap = resolve(process.argv[2] ?? "../knap");
const vendor = resolve("src/vendor");
const commit = execFileSync("git", ["-C", knap, "rev-parse", "--short", "HEAD"]).toString().trim();
const label = `obsidianmd/knap@${commit}`;
const license = "MIT License; see ./LICENSE.";

// Obsidian's review lints every source file and rejects suppressions.
const lintFixes = [
  [String.raw`([\w.\[\]]+)`, String.raw`([\w.[\]]+)`],
  [String.raw`/^[\w.$*+\/-]*/`, String.raw`/^[\w.$*+/-]*/`],
  ["Array.isArray(value) ? value : []);", "Array.isArray(value) ? value as unknown[] : []);"],
  ["const label: string = quoted ? JSON.parse(value) : value;", "const label = quoted ? JSON.parse(value) as string : value;"],
];

await fs.mkdir(vendor, { recursive: true });
await fs.copyFile(join(knap, "LICENSE"), join(vendor, "LICENSE"));

for (const name of ["playground-completions.ts", "playground-pairs.ts"]) {
  const file = `website/src/lib/${name}`;
  let source = await fs.readFile(join(knap, file), "utf8");

  const changes = name === "playground-completions.ts" ? [["'../../../src/tokenizer'", "'knap'"], ...lintFixes] : [];

  for (const [from, to] of changes) {
    if (!source.includes(from)) throw new Error(`Change no longer applies in ${file}: ${from}`);
    source = source.replace(from, to);
  }

  const changed = changes.length > 0 ? "Changed by scripts/update-knap-editor.mjs: the tokenizer import, and four lines Obsidian's review lint rejects." : "Unchanged.";

  await fs.writeFile(join(vendor, name), `// Copied from ${label}, ${file}. ${license}\n// ${changed}\n${source}`);
}

const bundle = join(vendor, ".filter-completions.mjs");

await esbuild.build({ entryPoints: [join(knap, "website/lib/filter-completions.ts")], bundle: true, format: "esm", platform: "node", packages: "external", outfile: bundle, logLevel: "silent" });
const { playgroundFilterSuggestions } = await import(pathToFileURL(bundle).href);

await fs.rm(bundle);
await fs.writeFile(join(vendor, "filter-suggestions.ts"),
  `// Generated by scripts/update-knap-editor.mjs from ${label}, website/lib/filter-completions.ts. ${license}\nimport type { TemplateSuggestion } from './playground-completions';\n\nexport const filterSuggestions: TemplateSuggestion[] = ${JSON.stringify(playgroundFilterSuggestions, null, 2)};\n`);
console.log(`Vendored knap@${commit}: ${playgroundFilterSuggestions.length} filters`);
