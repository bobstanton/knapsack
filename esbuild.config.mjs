import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { promises as fs } from "fs";

const mode = process.argv[2];
const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  minify: mode === "production",
  sourcemap: mode === "production" ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [{
    name: "rename-bundled-css",
    setup(build) {
      build.onEnd(async () => {
        await fs.rename("main.css", "styles.css").catch(error => { if (error.code !== "ENOENT") console.error("Error renaming bundled CSS:", error); });
      });
    },
  }],
});

if (mode === "watch") await context.watch();
else {
  await context.rebuild();
  process.exit(0);
}
